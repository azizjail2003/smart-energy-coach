"""
Repository layer for Subsystem 3.
Implements the data access methods required by S1 (Analytics) and S3 (AI Coach)
"""

from typing import Dict, Optional
from datetime import datetime
from sqlalchemy.orm import Session, sessionmaker
from sqlalchemy.exc import SQLAlchemyError
from subsystems.s3_coach.s3_models import (
    EnergyLog, Alert, AIRecommendation, Setting, DeviceCategory, ToneEnum, SourceEnum
)
from subsystems.s3_coach.s3_errors import S3ConfigurationError, S3DatabaseError
import os
from sqlalchemy import create_engine
from subsystems.s3_coach.s3_models import Base
from dotenv import load_dotenv

class MySQLRepository:
    """Implementation of the EnergyRepository using SQLAlchemy."""
    
    def __init__(self, session: Session):
        """
        Initializes the repository with a database session.
        State initialization is protected by property setters.
        """
        self._session = None
        self._setup_repository(session)

    def _setup_repository(self, session: Session) -> None:
        """Internal setup method for state configuration."""
        self.session = session

    @property
    def session(self) -> Session:
        """Retrieves the active SQLAlchemy session."""
        return self._session

    @session.setter
    def session(self, value: Session) -> None:
        """Validates and sets the SQLAlchemy session, raising custom errors on failure."""
        if value is None:
            raise S3ConfigurationError("A valid SQLAlchemy session must be provided.")
        self._session = value

    # --- Settings & Alert Limits ---

    def get_limits(self, building_id: str) -> Dict[str, float]:
        """
        Retrieves the alert limits for a specific building.
        Returns a dictionary mapping device category names to their limit in kWh.
        """
        try:
            settings = self.session.query(Setting).filter_by(building_id=building_id).all()
            return {s.device_category.value: float(s.alert_limit_kwh) for s in settings}
        except SQLAlchemyError as exc:
            raise S3DatabaseError(f"Failed to fetch limits: {exc}") from exc

    def save_limits(self, building_id: str, limits: Dict[str, float]) -> None:
        """
        Saves or updates alert limits for a given building.
        Expects a dictionary like {'HVAC': 15.5, 'Lighting': 10.0}.
        """
        try:
            for category_name, limit_val in limits.items():
                category_enum = DeviceCategory(category_name)
                
                # Check if a setting for this building and category already exists
                setting = self.session.query(Setting).filter_by(
                    building_id=building_id, 
                    device_category=category_enum
                ).first()
                
                if setting:
                    setting.alert_limit_kwh = limit_val
                else:
                    new_setting = Setting(
                        building_id=building_id,
                        device_category=category_enum,
                        alert_limit_kwh=limit_val
                    )
                    self.session.add(new_setting)
                    
            # Commit the transaction to save all limits safely
            self.session.commit()
        except SQLAlchemyError as exc:
            self.session.rollback()
            raise S3DatabaseError(f"Failed to save limits: {exc}") from exc

    # --- Time-Series Data & Alerts ---

    def save_energy_log(self, building_id: str, device_id: int, timestamp: datetime,
                        consumption: float, co2: float, temp: Optional[float] = None, 
                        comfort: Optional[float] = None) -> None:
        """
        Persists a new energy consumption reading generated by S1 (Analytics).
        Handles optional fields like temperature and comfort index smoothly.
        """
        try:
            new_log = EnergyLog(
                building_id=building_id,
                device_id=device_id,
                ts=timestamp,
                consumption_kwh=consumption,
                co2_emissions_kg=co2,
                indoor_temp_c=temp,
                comfort_index=comfort
            )
            self.session.add(new_log)
            self.session.commit()
        except SQLAlchemyError as exc:
            self.session.rollback()
            raise S3DatabaseError(f"Failed to save energy log: {exc}") from exc

    def save_alert(self, building_id: str, timestamp: datetime, alert_type: str, 
                   message: str, threshold: float, value: float) -> None:
        """
        Records an anomaly or efficiency drop detected by S1.
        S2 (Dashboard) read these to display notifications.
        """
        try:
            new_alert = Alert(
                building_id=building_id,
                ts=timestamp,
                alert_type=alert_type,
                message=message,
                threshold_kwh=threshold,
                value_kwh=value
            )
            self.session.add(new_alert)
            self.session.commit()
        except SQLAlchemyError as exc:
            self.session.rollback()
            raise S3DatabaseError(f"Failed to save alert: {exc}") from exc

    # --- AI Recommendations & Caching ---

    def get_cached_recommendation(self, building_id: str, context_hash: str) -> Optional[str]:
        """
        Checks if an identical AI request was made recently.
        Returns the cached JSON response string if found, otherwise None.
        """
        if not building_id or not context_hash:
            raise S3ConfigurationError("building_id and context_hash are required for cache lookup.")
        try:
            cached = (
                self.session.query(AIRecommendation)
                .filter_by(building_id=building_id, context_hash=context_hash)
                .order_by(AIRecommendation.created_at.desc())
                .first()
            )
            return cached.response_text if cached else None
        except SQLAlchemyError as exc:
            raise S3DatabaseError(f"Failed to query cached recommendation: {exc}") from exc

    def save_ai_recommendation(self, building_id: str, context_hash: str, tone: str, 
                               response: str, source: str, tokens: int = 0) -> None:
        """
        Saves a new AI recommendation to the database.
        'source' indicates if this came from 'openai', 'fallback', or 'cache'.
        """
        try:
            tone_enum = ToneEnum(tone)
            source_enum = SourceEnum(source)
        except ValueError as exc:
            raise S3ConfigurationError(f"Invalid tone or source value: {exc}") from exc

        try:
            new_rec = AIRecommendation(
                building_id=building_id,
                created_at=datetime.now(),
                tone=tone_enum,
                context_hash=context_hash,
                response_text=response,
                source=source_enum,
                tokens_used=tokens
            )
            self.session.add(new_rec)
            self.session.commit()
        except SQLAlchemyError as exc:
            self.session.rollback()
            raise S3DatabaseError(f"Failed to save AI recommendation: {exc}") from exc

def get_session() -> Session:
    """
    Loads database configuration from the .env file, initializes the SQLAlchemy engine,
    creates the necessary tables if they do not exist, and returns a new Session.
    
    If DATABASE_URL is not set, it defaults to a local SQLite file for easy testing.
    """
    # Load environment variables from .env file
    load_dotenv()

    # Get the connection string, default to SQLite if not provided in .env
    db_url = os.getenv("DATABASE_URL", "sqlite:///smart_energy.db")

    # Create the SQLAlchemy engine
    engine = create_engine(db_url)

    # Ensure all tables defined in S3 models are created in the database
    Base.metadata.create_all(engine)

    # Create a session factory bound to this engine
    SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    
    # Return a new session instance for S2 to use
    return SessionLocal()